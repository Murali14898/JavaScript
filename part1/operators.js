//Increment and Decrement Operators
let count = 5;
count++; // Equivalent to count = count + 1
count--; // Equivalent to count = count - 1
++count; // Pre-increment: increments count by 1 and returns the new value
--count; // Pre-decrement: decrements count by 1 and returns the new value

